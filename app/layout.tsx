export default function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  return (
    // suppressHydrationWarning: the boot script below sets data-theme and the theme variables on
    // <html> before React hydrates, so the attributes intentionally differ from the server's.
    <html lang="en" suppressHydrationWarning>
      <head>
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <meta name="theme-color" content="#ffffff" />
        {/* Apply the visitor's saved theme before first paint (see lib/theme-config.ts). */}
        <script dangerouslySetInnerHTML={{ __html: themeBootScript() }} />
        <meta name="color-scheme" content="light" />

        {/* Google Analytics, loaded after the page is idle: it is 194 KB and consent is denied by
            default, so nothing is lost by taking it off the critical path. */}
        {process.env.NEXT_PUBLIC_GA_ID && (
          <>
            <Script
              id="gtag-base"
              strategy="lazyOnload"
              src={`https://www.googletagmanager.com/gtag/js?id=${process.env.NEXT_PUBLIC_GA_ID}`}
            />
            <Script
              id="gtag-init"
              strategy="lazyOnload"
              dangerouslySetInnerHTML={{
                __html: `
                  window.dataLayer = window.dataLayer || [];
                  function gtag(){dataLayer.push(arguments);}
                  
                  // No analytics cookies until the visitor accepts (ConsentDialog / ConsentBar
                  // store the answer under 'gdpr-consent'; see /privacy#cookies).
                  gtag('consent', 'default', {
                    'analytics_storage': 'denied',
                    'ad_storage': 'denied',
                    'ad_user_data': 'denied',
                    'ad_personalization': 'denied',
                    'wait_for_update': 500
                  });
                  try {
                    if (localStorage.getItem('gdpr-consent') === 'accepted') {
                      gtag('consent', 'update', { 'analytics_storage': 'granted' });
                    }
                  } catch (e) {}

                  gtag('js', new Date());
                  gtag('config', '${process.env.NEXT_PUBLIC_GA_ID}', {
                    anonymize_ip: true,
                    allow_google_signals: false,
                    allow_ad_personalization_signals: false,
                    cookie_flags: 'SameSite=None;Secure'
                  });
                `,
              }}
            />
          </>
        )}

        {/* Site-wide structured data. Pages add their own graph (BreadcrumbList, WebPage, FAQPage)
            and reference the organisation by @id; a site-wide FAQPage used to sit here and claimed
            FAQ markup for Q&As that were not visible on most pages, so pages that genuinely show
            FAQs declare their own. */}
        <JsonLd data={SITE_LD} />

        {/* Favicon and app icons */}
        {/* ?v= busts the year-long nginx cache on these files. Bump it whenever
            the icon artwork changes, or returning visitors keep the old one. */}
        <link rel="icon" type="image/png" sizes="32x32" href="/favicon.png?v=2" />
        <link rel="icon" type="image/png" sizes="16x16" href="/favicon.png?v=2" />
        <link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png?v=2" />
        <link rel="shortcut icon" href="/favicon.png?v=2" />
        <meta name="msapplication-TileImage" content="/apple-touch-icon.png?v=2" />
        <meta name="msapplication-TileColor" content="#1a73e8" />
      </head>
      <body>
        <Providers>
          <VisitorTracker />
          {/* Grows to fill the window, so on a short page the footer sits at the bottom of the
              window rather than straight under the content (styles/site-footer.css). */}
          <div className="site-main">{children}</div>
          <SiteFooter />
        </Providers>
      </body>
    </html>
  )
}
